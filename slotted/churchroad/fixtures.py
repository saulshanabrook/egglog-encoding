"""Check pinned Churchroad inputs and regenerate the runnable slotted fixtures.

python3 -m slotted.churchroad.fixtures --write
python3 -m slotted.churchroad.fixtures --check-native /tmp/rca/input.egg --case ripple-adder
"""

import argparse
import hashlib
import json
from pathlib import Path

from slotted.reference import parse, render

from .importer import import_egg
from .modules import LANGUAGE, LANGUAGE_PATH, enumerate_modules, program

ROOT = Path(__file__).resolve().parents[2]
DIRECTORY = Path(__file__).with_name("fixtures")
BENCHES = ROOT / "egglog-experimental/benches/slotted/churchroad"
CASES = {
    "half-adder": ("half_adder.egg", ("o_sum", "o_carry")),
    "ripple-adder": ("ripple-adder.egg", ()),
    "wide-mul": ("wide-mul.egg", ()),
}


def verify_inputs():
    provenance = json.loads((DIRECTORY / "provenance.json").read_text())
    for name, record in {**provenance["sources"], **provenance["generated"]}.items():
        if hashlib.sha256((DIRECTORY / name).read_bytes()).hexdigest() != record["sha256"]:
            raise ValueError(f"Churchroad fixture hash changed: {name}")
    return provenance


def fixture_text(case):
    provenance = verify_inputs()
    name, outputs = CASES[case]
    circuit = import_egg((DIRECTORY / name).read_text(), outputs)
    candidates, omitted = enumerate_modules(circuit)
    assert not omitted
    source = program(circuit, candidates)
    include = f'(include "{LANGUAGE_PATH.relative_to(ROOT)}")\n'
    return (
        f"; Generated by python3 -m slotted.churchroad.fixtures --write\n"
        f"; Churchroad {provenance['revision']}; MIT, copyright Gus Henry Smith.\n"
        f"; Source/provenance/license: slotted/churchroad/fixtures/{name}, provenance.json, LICENSE-Churchroad-MIT.\n"
        + source.replace(LANGUAGE, include, 1)
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check-native", type=Path)
    parser.add_argument("--case", choices=CASES, default="ripple-adder")
    args = parser.parse_args()
    verify_inputs()
    if args.check_native:
        expected = (DIRECTORY / CASES[args.case][0]).read_text()

        def normalize(text):
            return "\n".join(render(form) for form in parse(text))

        if normalize(args.check_native.read_text()) != normalize(expected):
            raise ValueError("native Churchroad commands differ from the saved fixture")
    BENCHES.mkdir(exist_ok=True)
    for case in CASES:
        path = BENCHES / f"{case}.egg"
        text = fixture_text(case)
        if args.write:
            path.write_text(text)
        elif path.read_text() != text:
            raise ValueError(f"stale slotted fixture: {path}; regenerate with --write")
    print("Churchroad provenance and generated slotted fixtures match.")


if __name__ == "__main__":
    main()
