#!/usr/bin/env python3
"""Generate source fixtures and desugared snapshots for disequality tests."""

from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import tempfile
from pathlib import Path

ENCODINGS = ("ee", "oee", "nee", "de")
TREATMENTS = {
    "ordinary": (),
    "term": ("--term-encoding",),
    "proofs": ("--proofs",),
    "proof-testing": ("--proof-testing",),
    "proof-extraction": ("--proof-extraction",),
}
SUPPORTED_TREATMENTS = {encoding: tuple(TREATMENTS) if encoding != "de" else ("ordinary",) for encoding in ENCODINGS}
PARAMETER_FACTS = {
    "config.tsv": "2\n",
    "f.tsv": "3\t2\n5\t4\n",
    "g.tsv": "8\t6\t7\n11\t9\t10\n",
    "h.tsv": "15\t12\t13\t14\n19\t16\t17\t18\n",
    "numerals.tsv": ("0\t1\n1\t2\n2\t1\n4\t2\n6\t1\n7\t2\n9\t2\n10\t1\n12\t1\n13\t2\n14\t3\n16\t1\n17\t2\n18\t3\n"),
    "pairs.tsv": "0\t0\t1\n1\t3\t5\n2\t8\t11\n3\t15\t19\n",
}
EUF_HEADER = (
    b";; Generated by benchmarks/disequality/scripts/generate_snapshots.py from\n"
    b";; benchmarks/disequality/euf-solver/tests/sat.smt2. This is the single\n"
    b";; MiniSat model produced by the Dis/Equality Graphs EUF artifact integration,\n"
    b";; rendered as an outcome-preserving chronological host replay with direct constructors.\n"
)


def run_checked(command: list[str], description: str, success_suffix: str) -> None:
    process = subprocess.run(
        command,
        check=False,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
    )
    if process.returncode != 0:
        raise RuntimeError(f"{description} failed:\n{process.stdout}")
    if not any(line.strip().endswith(success_suffix) for line in process.stdout.splitlines()):
        raise RuntimeError(f"{description} produced no success marker:\n{process.stdout}")


def validate_direct_snapshot(contents: bytes, sort_name: str, description: str) -> None:
    source = contents.decode()
    required = (
        f"(sort {sort_name})",
        f"(constructor Atom (String) {sort_name})",
        "; Outcome-preserving chronological host interaction replay.",
        "; host consistency check:",
    )
    forbidden = ("BenchmarkNode", "BenchmarkTerms", "HostWitness", "HostTermAt", "vec-of")
    missing = [fragment for fragment in required if fragment not in source]
    present = [fragment for fragment in forbidden if fragment in source]
    if missing or present:
        raise RuntimeError(
            f"{description} is not a direct-constructor snapshot: missing={missing}, forbidden={present}",
        )


def replay_all_treatments(
    binary: Path,
    encoding: str,
    path: Path,
    fact_directory: Path | None,
    *,
    pass_encoding: bool,
) -> None:
    for treatment in SUPPORTED_TREATMENTS[encoding]:
        treatment_args = TREATMENTS[treatment]
        command = [str(binary), *treatment_args]
        if pass_encoding:
            command.extend(("--disequality-encoding", encoding))
        if fact_directory is not None:
            command.extend(("--fact-directory", str(fact_directory)))
        command.append(str(path))
        process = subprocess.run(
            command,
            check=False,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
        )
        if process.returncode != 0:
            raise RuntimeError(f"replaying {path} with {encoding}/{treatment} failed:\n{process.stdout}")


def replay_snapshots(binary: Path, output: Path) -> int:
    replay_count = 0
    with tempfile.TemporaryDirectory(prefix="egglog-parameter-facts-") as temporary:
        fact_directory = Path(temporary)
        for name, contents in PARAMETER_FACTS.items():
            (fact_directory / name).write_text(contents, encoding="utf-8")

        for path in sorted(output.glob("*.egg")):
            facts = fact_directory if path.name == "parameter-analysis.egg" else None
            for encoding in ENCODINGS:
                replay_all_treatments(binary, encoding, path, facts, pass_encoding=True)
                replay_count += len(SUPPORTED_TREATMENTS[encoding])

        for path in sorted((output / "snapshots").glob("*.desugared.egg")):
            facts = fact_directory if path.name.startswith("parameter-analysis.") else None
            encoding = next(encoding for encoding in ENCODINGS if path.name.endswith(f".{encoding}.desugared.egg"))
            replay_all_treatments(binary, encoding, path, facts, pass_encoding=False)
            replay_count += len(SUPPORTED_TREATMENTS[encoding])
    return replay_count


def generate(args: argparse.Namespace) -> dict[Path, bytes]:
    generated: dict[Path, bytes] = {}
    manifest: dict[str, object] = {
        "schema_version": 6,
        "encodings": list(ENCODINGS),
        "replay_treatments": {encoding: list(treatments) for encoding, treatments in SUPPORTED_TREATMENTS.items()},
        "euf": {},
        "propel": {},
    }
    host_desugared: dict[tuple[str, str], bytes] = {}
    with tempfile.TemporaryDirectory(prefix="egglog-disequality-snapshots-") as temporary:
        temporary_path = Path(temporary)

        euf_sources: list[bytes] = []
        euf_input = args.euf_input.resolve()
        for encoding in ENCODINGS:
            directory = temporary_path / "euf" / encoding
            directory.mkdir(parents=True)
            run_checked(
                [
                    str(args.euf_binary.resolve()),
                    "--backend",
                    f"egglog-{encoding}",
                    "--term-language",
                    "direct",
                    "--emit-source-dir",
                    str(directory),
                    str(euf_input),
                ],
                f"EUF {encoding}",
                ": sat",
            )
            raw = [path for path in sorted(directory.glob("*.egg")) if not path.name.endswith(".desugared.egg")]
            desugared = sorted(directory.glob("*.desugared.egg"))
            if len(raw) != 1 or len(desugared) != 1:
                raise RuntimeError(f"EUF {encoding} emitted {len(raw)} raw and {len(desugared)} desugared snapshots")
            raw_source = raw[0].read_bytes()
            validate_direct_snapshot(raw_source, "EufTerm", f"EUF {encoding}")
            euf_sources.append(raw_source)
            host_desugared[("euf-sat", encoding)] = desugared[0].read_bytes()
        if len(set(euf_sources)) != 1:
            raise RuntimeError("EUF encodings emitted different pre-desugaring programs")
        generated[Path("euf-sat.egg")] = EUF_HEADER + euf_sources[0]
        manifest["euf"] = {
            "input": "benchmarks/disequality/euf-solver/tests/sat.smt2",
            "input_sha256": hashlib.sha256(euf_input.read_bytes()).hexdigest(),
            "model_count": 1,
            "term_language": "direct",
            "recording": "outcome_preserving_chronological_replay",
        }

        propel_sources: list[bytes] = []
        graph_counts: list[int] = []
        propel_input = args.propel_input.resolve()
        selected_index: int | None = None
        for encoding in ENCODINGS:
            directory = temporary_path / "propel" / encoding
            directory.mkdir(parents=True)
            run_checked(
                [
                    str(args.propel_binary.resolve()),
                    "-f",
                    str(propel_input),
                    "--variant",
                    f"egglog-{encoding}",
                    "--term-language",
                    "direct",
                    "--emit-source-dir",
                    str(directory),
                ],
                f"Propel {encoding}",
                "Check successful.",
            )
            raw = [path for path in sorted(directory.glob("*.egg")) if not path.name.endswith(".desugared.egg")]
            desugared = sorted(directory.glob("*.desugared.egg"))
            if not raw or len(raw) != len(desugared):
                raise RuntimeError(f"Propel {encoding} emitted {len(raw)} raw and {len(desugared)} desugared snapshots")
            graph_counts.append(len(raw))
            index = len(raw) - 1 if args.propel_graph_index < 0 else args.propel_graph_index
            if index >= len(raw):
                raise RuntimeError(f"Propel graph index {index} is outside the {len(raw)} emitted graphs")
            selected_index = index
            raw_source = raw[index].read_bytes()
            validate_direct_snapshot(raw_source, "PropelTerm", f"Propel {encoding}")
            propel_sources.append(raw_source)
            host_desugared[("propel-gset-comm", encoding)] = desugared[index].read_bytes()
        if len(set(graph_counts)) != 1:
            raise RuntimeError(f"Propel encodings emitted different graph counts: {graph_counts}")
        if len(set(propel_sources)) != 1:
            raise RuntimeError("Propel encodings emitted different pre-desugaring programs")
        propel_header = (
            ";; Generated by benchmarks/disequality/scripts/generate_snapshots.py from\n"
            ";; benchmarks/disequality/inductive-prover/benchmarks/propel/gset_comm.propel,\n"
            ";; imported from the Dis/Equality Graphs artifact. This is graph\n"
            f";; {selected_index} of the {graph_counts[0]} graphs created by that run, rendered with\n"
            ";; direct constructors as an outcome-preserving chronological host replay.\n"
        ).encode()
        generated[Path("propel-gset-comm.egg")] = propel_header + propel_sources[0]
        manifest["propel"] = {
            "input": "benchmarks/disequality/inductive-prover/benchmarks/propel/gset_comm.propel",
            "input_sha256": hashlib.sha256(propel_input.read_bytes()).hexdigest(),
            "graph_count": graph_counts[0],
            "selected_graph_index": selected_index,
            "term_language": "direct",
            "recording": "outcome_preserving_chronological_replay",
        }

        source_files = {
            path.name: path.read_bytes()
            for path in sorted(args.output.glob("*.egg"))
            if path.name not in {"euf-sat.egg", "propel-gset-comm.egg"}
        }
        source_files["euf-sat.egg"] = generated[Path("euf-sat.egg")]
        source_files["propel-gset-comm.egg"] = generated[Path("propel-gset-comm.egg")]
        source_directory = temporary_path / "sources"
        source_directory.mkdir()
        snapshot_hashes: dict[str, str] = {}
        for source_name, source in sorted(source_files.items()):
            source_path = source_directory / source_name
            source_path.write_bytes(source)
            for encoding in ENCODINGS:
                completed = subprocess.run(
                    [
                        str(args.egglog_binary.resolve()),
                        "--disequality-encoding",
                        encoding,
                        "--mode",
                        "desugar",
                        str(source_path),
                    ],
                    check=True,
                    capture_output=True,
                )
                snapshot_name = f"{source_path.stem}.{encoding}.desugared.egg"
                snapshot_path = Path("snapshots") / snapshot_name
                generated[snapshot_path] = completed.stdout
                snapshot_hashes[snapshot_name] = hashlib.sha256(completed.stdout).hexdigest()
                host_snapshot = host_desugared.get((source_path.stem, encoding))
                if host_snapshot is not None and completed.stdout != host_snapshot:
                    raise RuntimeError(f"host and CLI desugaring differ for {source_path.stem}/{encoding}")

        manifest["sources"] = {
            name: {
                "sha256": hashlib.sha256(contents).hexdigest(),
                "generated_by_host_integration": name in {"euf-sat.egg", "propel-gset-comm.egg"},
            }
            for name, contents in sorted(source_files.items())
        }
        manifest["snapshots"] = snapshot_hashes

    generated[Path("snapshots/manifest.json")] = (json.dumps(manifest, indent=2, sort_keys=True) + "\n").encode()
    return generated


def main() -> int:
    root = Path(__file__).resolve().parents[3]
    case_study = root / "benchmarks" / "disequality"
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--euf-binary",
        type=Path,
        default=case_study / "euf-solver" / "target" / "debug" / "euf-solver",
    )
    parser.add_argument(
        "--euf-input",
        type=Path,
        default=case_study / "euf-solver" / "tests" / "sat.smt2",
    )
    parser.add_argument(
        "--propel-binary",
        type=Path,
        default=case_study / "inductive-prover" / "propel" / ".native" / "target" / "scala-3.4.2" / "propel",
    )
    parser.add_argument(
        "--egglog-binary",
        type=Path,
        default=root / "target" / "debug" / "egglog-experimental",
    )
    parser.add_argument(
        "--propel-input",
        type=Path,
        default=case_study / "inductive-prover" / "benchmarks" / "propel" / "gset_comm.propel",
    )
    parser.add_argument("--propel-graph-index", type=int, default=-1)
    parser.add_argument(
        "--output",
        type=Path,
        default=root / "egglog-experimental" / "tests" / "disequality",
    )
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--force", action="store_true")
    mode.add_argument("--replay", action="store_true")
    args = parser.parse_args()
    required_binaries = (
        (args.egglog_binary,) if args.replay else (args.euf_binary, args.propel_binary, args.egglog_binary)
    )
    for binary in required_binaries:
        if not binary.is_file():
            parser.error(f"binary does not exist: {binary}")

    if args.replay:
        if not args.output.is_dir():
            parser.error(f"output directory does not exist: {args.output}")
        replay_count = replay_snapshots(args.egglog_binary.resolve(), args.output)
        print(f"replayed {replay_count} treatments from {args.output}")
        return 0

    generated = generate(args)
    tracked_outputs = [
        args.output / "euf-sat.egg",
        args.output / "propel-gset-comm.egg",
        *(args.output / "snapshots").glob("*"),
    ]
    existing = {path.relative_to(args.output): path.read_bytes() for path in tracked_outputs if path.is_file()}
    if args.check:
        if generated != existing:
            missing = sorted(str(path) for path in generated.keys() - existing.keys())
            extra = sorted(str(path) for path in existing.keys() - generated.keys())
            changed = sorted(
                str(path) for path in generated.keys() & existing.keys() if generated[path] != existing[path]
            )
            raise SystemExit(f"snapshot mismatch: missing={missing}, extra={extra}, changed={changed}")
        replay_count = replay_snapshots(args.egglog_binary.resolve(), args.output)
        print(f"verified {len(generated)} files and replayed {replay_count} treatments in {args.output}")
        return 0

    snapshots = args.output / "snapshots"
    snapshots.mkdir(parents=True, exist_ok=True)
    for path in existing.keys() - generated.keys():
        (args.output / path).unlink()
    for path, contents in generated.items():
        destination = args.output / path
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(contents)
    replay_count = replay_snapshots(args.egglog_binary.resolve(), args.output)
    print(f"wrote {len(generated)} files and replayed {replay_count} treatments in {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
