"""Regenerate self-contained slotted source inputs and exact native reference specs.

Run ``python -m benchmarks.slotted.generate`` from the repository root. Collection
only reads the checked-in inputs; it never imports this generator or slotted's
graph verification machinery.
"""

from __future__ import annotations

import argparse
import importlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
INPUTS = Path(__file__).resolve().parent / "inputs"
reference = importlib.import_module("slotted.reference")
workloads = importlib.import_module("slotted.workloads")


def frozen_inputs() -> dict[Path, str]:
    """Expand source includes and retain each workload's exact schedule and goal."""

    def expand(source: str) -> list[str]:
        forms = []
        for form in reference.parse(source):
            if form[0] == "include":
                forms.extend(expand((ROOT / json.loads(form[1])).read_text()))
            else:
                forms.append(reference.render(form))
        return forms

    selected = workloads.select(
        argparse.Namespace(
            study="all", case=None, rounds=None, kernel=workloads.pf.KERNELS, phase=workloads.pf.PHASES, rules=44
        )
    )
    result = {}
    for workload in selected:
        path = Path(workload.study) / f"{workload.case}.egg"
        result[path] = (
            "; Generated by python -m benchmarks.slotted.generate.\n" + "\n".join(expand(workload.program)) + "\n"
        )
        result[path.with_suffix(".ref")] = (
            json.dumps(
                {
                    "multi": workload.multi,
                    "nested": workload.nested,
                    "unsupported_reason": workload.unsupported.get("ref-nested", ""),
                },
                indent=2,
                ensure_ascii=False,
            )
            + "\n"
        )
    return result


def main() -> None:
    """Write the complete input suite without building or running an executable."""
    for relative, source in frozen_inputs().items():
        path = INPUTS / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(source)


if __name__ == "__main__":
    main()
